<?php
declare(strict_types=1);

namespace Winglet\Core\Http\Routing;

use Winglet\Core\Support\ControllerScanner;
use Winglet\Core\Support\Config;

/**
 * Rakentaa deterministisen controller-listan eri lähteistä ja kirjoittaa sen PHP-tiedostoksi.
 *
 * Lähteet:
 * - App controller scan (App\)
 * - Framework internal controllers (staattinen lista tai scan)
 * - Modules/plugins (config)
 *
 * Tuottaa:
 * - var/controllers.php
 * - var/routes.php (rebuild aina kun controllers-lista päivitetään)
 */
final class ControllerMapBuilder
{
    public function __construct(
        private readonly ControllerScanner $scanner = new ControllerScanner()
    ) {}

    /** @return array<int, class-string> */
    public function buildAndWrite(
        Config $config,
        string $basePath,
        string $controllersFile,
        string $routesFile
    ): array {
        $classes = [];

        // 1) App controllers (scan)
        $appNs  = (string)$config->get('controllers.app.namespace', 'App\\Controller\\');
        $appDir = (string)$config->get('controllers.app.baseDir', $basePath . '/src');
        $appSub = (string)$config->get('controllers.app.subDir', 'Controller');

        $appClasses = $this->scanner->scan($appNs, $appDir, $appSub);

        $classes = array_merge($classes, $appClasses);

        // 2) Framework internal controllers (staattinen lista = nopein ja turvallisin)
        $internal = (array)$config->get('controllers.framework.list', [
            \Winglet\Core\Http\Controller\HealthController::class,
            \Winglet\Core\Http\Controller\ReadinessController::class,
            \Winglet\Core\Http\Controller\EchoController::class,
            \Winglet\Core\Http\Controller\DevToolsController::class,
        ]);
        $classes = array_merge($classes, $internal);

        // 3) Modules / plugins (config)
        $modules = $config->get('modules', []);
        if (is_array($modules)) {
            foreach ($modules as $mod) {
                if (!is_array($mod)) {
                    continue;
                }

                $enabled = (bool)($mod['enabled'] ?? true);
                if (!$enabled) {
                    continue;
                }

                $ns  = (string)($mod['namespace'] ?? '');
                $dir = (string)($mod['baseDir'] ?? '');
                $sub = (string)($mod['subDir'] ?? 'Controller');

                if ($ns === '' || $dir === '') {
                    continue;
                }

                if (!str_starts_with($dir, '/')) {
                    $dir = rtrim($basePath, '/') . '/' . ltrim($dir, '/');
                }

                $classes = array_merge($classes, $this->scanner->scan($ns, $dir, $sub));

                $staticList = $mod['list'] ?? null;
                if (is_array($staticList)) {
                    $classes = array_merge($classes, $staticList);
                }
            }
        }

        $classes = array_values(array_unique(array_filter(
            $classes,
            static fn($c) => is_string($c) && class_exists($c)
        )));
        /** @var array<int, class-string> $classes */
        sort($classes);

        $this->writePhpArrayFile($classes, $controllersFile);

        (new RouteMapBuilder())->build($classes, $routesFile);

        return $classes;
    }

    /** @param array<int, class-string> $classes */
    private function writePhpArrayFile(array $classes, string $outputPhpFile): void
    {
        $php = "<?php\n// generated by ControllerMapBuilder\nreturn " . var_export($classes, true) . ";\n";
        @mkdir(dirname($outputPhpFile), 0775, true);
        file_put_contents($outputPhpFile, $php);
    }
}
