<?php
declare(strict_types=1);

namespace Winglet\Core\Http\Routing;

use ReflectionClass;
use ReflectionMethod;
use Winglet\Core\Http\Routing\Attributes\Route as RouteAttr;
use Winglet\Core\Security\AccessControl\Attributes\Access as AccessAttr;

/**
 * Rakentaa reittikartan controller-luokista (attribuutit).
 *
 * Kutsutaan:
 * - CLI:llä build-vaiheessa / kehityksessä
 * - (optionaalisesti) dev HTTP endpointista
 */
final class RouteMapBuilder
{
    /**
     * @param array<int, class-string> $controllerClasses FQCN-lista controllereista (app generoi tämän esim. autoload/scan)
     */
    public function build(array $controllerClasses, string $outputPhpFile): void
    {
        $routes = [
            'static' => [],   // [METHOD][PATH] => routeData
            'dynamic' => [],  // [METHOD] => [routeData...]
        ];

        foreach ($controllerClasses as $class) {
            if (!class_exists($class)) continue;

            $rc = new ReflectionClass($class);
            foreach ($rc->getMethods(ReflectionMethod::IS_PUBLIC) as $m) {
                $methodName = $m->getName();

                // ✅ Important change:
                // Do NOT restrict to "handle*" methods.
                // Any public method with #[Route] is eligible.
                $routeAttrs = $m->getAttributes(RouteAttr::class);
                if (!$routeAttrs) continue;

                $accessAttr = $m->getAttributes(AccessAttr::class);
                $access = $accessAttr ? $accessAttr[0]->newInstance() : null;

                // Infer defaults only if Route doesn't set methods
                $defaultMethods = $this->inferMethodsFromHandlerName($methodName);

                foreach ($routeAttrs as $ra) {
                    /** @var RouteAttr $r */
                    $r = $ra->newInstance();
                    $methods = $r->methods ?: $defaultMethods;

                    foreach ($methods as $httpMethod) {
                        $httpMethod = strtoupper($httpMethod);
                        $routeData = $this->compileRoute(
                            method: $httpMethod,
                            path: $r->path,
                            controller: $class,
                            action: $methodName,
                            access: $access
                        );

                        $this->addRoute($routes, $routeData);
                    }
                }
            }
        }

        // Priorisointi: staattiset aina ensin (se on jo erillinen),
        // dynaamisissa voidaan vielä järjestää "spesifisyys" (vähemmän muuttujia ensin)
        foreach ($routes['dynamic'] as $m => $list) {
            usort($list, fn($a, $b) => $a['dynamic_weight'] <=> $b['dynamic_weight']);
            $routes['dynamic'][$m] = $list;
        }

        $php = "<?php\n// generated by RouteMapBuilder\nreturn " . var_export($routes, true) . ";\n";
        @mkdir(dirname($outputPhpFile), 0775, true);
        file_put_contents($outputPhpFile, $php);
    }

    /** @return list<string> */
    private function inferMethodsFromHandlerName(string $methodName): array
    {
        // Keep legacy handler-based inference:
        // - handle => GET+POST
        // - handleGet => GET, handlePost => POST, etc.
        if ($methodName === 'handle') {
            return ['GET', 'POST'];
        }
        if (preg_match('/^handle([A-Z][a-zA-Z0-9]*)$/', $methodName, $m)) {
            return [strtoupper($m[1])];
        }

        // ✅ For non-handle methods, safest default is GET only.
        return ['GET'];
    }

    /**
     * @param class-string $controller
     * @return array{
     *   method: string,
     *   path: string,
     *   controller: class-string,
     *   action: string,
     *   is_dynamic: bool,
     *   regex: string|null,
     *   params: array<int, string>,
     *   dynamic_weight: int,
     *   access: array{min:int|null,max:int|null,groups:array<int,string>,checker:string|null}|null
     * }
     */
    private function compileRoute(string $method, string $path, string $controller, string $action, ?object $access): array
    {
        if (!class_exists($controller)) {
            // Builder should only pass existing classes
            throw new \RuntimeException("Controller class does not exist: {$controller}");
        }
        /** @var class-string $controller */

        // Muuttujat: {id}
        $paramNames = [];
        $isDynamic = str_contains($path, '{');

        $regex = null;
        $weight = 0;

        if ($isDynamic) {
            $pattern = preg_replace_callback('/\{([a-zA-Z_][a-zA-Z0-9_]*)\}/', function ($m) use (&$paramNames, &$weight) {
                $paramNames[] = $m[1];
                $weight++; // enemmän muuttujia => isompi weight => myöhemmin
                return '(?P<' . $m[1] . '>[^/]+)';
            }, $path);

            $regex = '~^' . $pattern . '$~';
        }

        $accessArr = null;
        if ($access) {
            /** @var \Winglet\Core\Security\AccessControl\Attributes\Access $access */
            $accessArr = [
                'min' => $access->minLevel,
                'max' => $access->maxLevel,
                'groups' => $access->groups,
                'checker' => $access->checker,
            ];
        }

        return [
            'method' => $method,
            'path' => $path,
            'controller' => $controller,
            'action' => $action,
            'is_dynamic' => $isDynamic,
            'regex' => $regex,
            'params' => $paramNames,
            'dynamic_weight' => $weight,
            'access' => $accessArr,
        ];
    }

    private function handlerSpecificity(string $actionMethod): int
    {
        // suurempi = “voittaa”
        //
        // We prefer explicit method names over legacy handler conventions:
        // - any non-handle method (e.g. getSession) = 3 (most specific)
        // - handleGet/handlePost/... = 2
        // - handle (general) = 1
        if ($actionMethod === 'handle') return 1;
        if (str_starts_with($actionMethod, 'handle')) return 2;
        return 3;
    }

    private function addRoute(array &$routes, array $routeData): void
    {
        $m = $routeData['method'];
        $path = $routeData['path'];

        if ($routeData['is_dynamic'] === false) {
            $existing = $routes['static'][$m][$path] ?? null;
            if ($existing === null) {
                $routes['static'][$m][$path] = $routeData;
                return;
            }

            // Dedup: more specific handler wins
            $newSpec = $this->handlerSpecificity($routeData['action']);
            $oldSpec = $this->handlerSpecificity($existing['action'] ?? 'handle');

            if ($newSpec > $oldSpec) {
                $routes['static'][$m][$path] = $routeData;
            }
            return;
        }

        // Dynamic: jos sama regex+method+path syntyy kahdesti, pidä spesifimpi
        $routes['dynamic'][$m] ??= [];

        foreach ($routes['dynamic'][$m] as $i => $ex) {
            if (($ex['path'] ?? null) === $path && ($ex['regex'] ?? null) === $routeData['regex']) {
                $newSpec = $this->handlerSpecificity($routeData['action']);
                $oldSpec = $this->handlerSpecificity($ex['action'] ?? 'handle');

                if ($newSpec > $oldSpec) {
                    $routes['dynamic'][$m][$i] = $routeData;
                }
                return;
            }
        }

        $routes['dynamic'][$m][] = $routeData;
    }
}