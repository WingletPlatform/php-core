<?php
declare(strict_types=1);

namespace Winglet\Core\Support;

/**
 * Skannaa controller-luokat PSR-4 poluista ja palauttaa FQCN-listan.
 *
 * Nopeus:
 * - tämä ajetaan build/dev-työkaluna, ei jokaisessa requestissa.
 *
 * Tyypillinen käyttö:
 * - scan('App\\', /var/www/App/src)
 * - scan('Winglet\\Core\\', /var/www/Winglet/src) (jos haluat myös frameworkin controllerit)
 */
final class ControllerScanner
{
    /**
     * @return string[] FQCN-lista
     */
    public function scan(string $namespacePrefix, string $baseDir, string $subDir = 'Controller'): array
    {
        $baseDir = rtrim($baseDir, '/');
        $root = $baseDir . '/' . trim($subDir, '/');

        if (!is_dir($root)) {
            return [];
        }

        $files = $this->phpFiles($root);

        $classes = [];
        foreach ($files as $file) {
            $fqcn = $this->extractFqcn($file);
            if ($fqcn === null) continue;

            // filter: haluttu namespace prefix
            if (!str_starts_with($fqcn, $namespacePrefix)) continue;

            $classes[] = $fqcn;
        }

        sort($classes);
        return array_values(array_unique($classes));
    }

    /**
     * Tallentaa PHP-tiedostoksi: return [\FQCN::class, ...];
     *
     * @param string[] $classes
     */
    public function writePhpArrayFile(array $classes, string $outputPhpFile): void
    {
        $php = "<?php\n// generated by ControllerScanner\nreturn " . var_export($classes, true) . ";\n";
        @mkdir(dirname($outputPhpFile), 0775, true);
        file_put_contents($outputPhpFile, $php);
    }

    /** @return string[] */
    private function phpFiles(string $root): array
    {
        $out = [];
        $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root));
        foreach ($it as $f) {
            if (!$f->isFile()) continue;
            $p = $f->getPathname();
            if (!str_ends_with($p, '.php')) continue;
            $out[] = $p;
        }
        return $out;
    }

    private function extractFqcn(string $file): ?string
    {
        $code = @file_get_contents($file);
        if ($code === false || $code === '') return null;

        $tokens = token_get_all($code);

        $ns = '';
        $class = null;

        $count = count($tokens);
        for ($i = 0; $i < $count; $i++) {
            $t = $tokens[$i];

            if (is_array($t) && $t[0] === T_NAMESPACE) {
                $ns = '';
                for ($j = $i + 1; $j < $count; $j++) {
                    $tt = $tokens[$j];

                    if (is_array($tt) && in_array($tt[0], [T_STRING, T_NAME_QUALIFIED, T_NS_SEPARATOR], true)) {
                        $ns .= $tt[1];
                    } elseif ($tt === '\\') {
                        $ns .= '\\';
                    } elseif ($tt === ';') {
                        break;
                    }
                }
                $ns = trim($ns, '\\');
            }

            if (is_array($t) && $t[0] === T_CLASS) {
                // Skip anonymous classes
                $prev = $tokens[$i - 1] ?? null;
                if (is_array($prev) && $prev[0] === T_NEW) {
                    continue;
                }

                for ($j = $i + 1; $j < $count; $j++) {
                    $tt = $tokens[$j];
                    if (is_array($tt) && $tt[0] === T_STRING) {
                        $class = $tt[1];
                        break 2;
                    }
                }
            }
        }

        if ($class === null) return null;
        return $ns === '' ? $class : ($ns . '\\' . $class);
    }
}